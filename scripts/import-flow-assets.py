"""Import Google Flow images into the visual library.

    python scripts/import-flow-assets.py <folder-with-images>

For every image: removes the flat white/black background (transparent WebP, 384px),
takes keywords from the descriptive file name, and writes the index used by the
engine to src/engine/libraryData.js. Re-running adds new images and keeps old ones.
"""
import json
import re
import sys
from collections import deque
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / 'public' / 'library'
INDEX = ROOT / 'src' / 'engine' / 'libraryData.js'
HEADER = '// Generated by scripts/import-flow-assets.py — do not edit by hand.\nexport default '
SIZE = 384
MAX_VARIANTS = 3

# Words in Flow's file names that describe the render, not the object.
NOISE = set('''centered centred rendered render renders displayed display object objects on white black background
back backgr backgro backgrou backgroun bac ba b wh whi whit bla blac a an of the 3d icon single image isolated and in
with at shown showing glossy premium style view illustration graphic symbol clean minimal flat
rendering studio gentle refl floating backg centrally burning model product blank small making giving wearing pose'''.split())


def keywords_from(name):
    stem = re.sub(r'_\d{8,}(_\d+)?$', '', Path(name).stem)
    words = [w for w in re.split(r'[^a-z0-9]+', stem.lower().replace('…', ' ')) if w and not w.isdigit()]
    return [w for w in words if w not in NOISE]


def background(img):
    w, h = img.size
    pts = [(4, 4), (w - 5, 4), (4, h - 5), (w - 5, h - 5), (w // 2, 4), (4, h // 2), (w - 5, h // 2)]
    px = [img.getpixel(p) for p in pts]
    return tuple(sorted(c[i] for c in px)[len(px) // 2] for i in range(3))


def cut_out(img):
    """Make the border-connected background transparent, with soft edges for shadows."""
    img = img.convert('RGB').resize((SIZE, SIZE), Image.LANCZOS)
    bg = background(img)
    w, h = img.size
    pix = img.load()
    diff = [[max(abs(pix[x, y][i] - bg[i]) for i in range(3)) for x in range(w)] for y in range(h)]
    near = 40  # pixels this close to the background colour can be (partly) transparent
    seen = [[False] * w for _ in range(h)]
    q = deque((x, y) for x in range(w) for y in (0, h - 1)) + deque((x, y) for y in range(h) for x in (0, w - 1))
    while q:
        x, y = q.popleft()
        if seen[y][x] or diff[y][x] > near:
            continue
        seen[y][x] = True
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < w and 0 <= ny < h and not seen[ny][nx]:
                q.append((nx, ny))
    out = Image.new('RGBA', (w, h))
    o = out.load()
    for y in range(h):
        for x in range(w):
            r, g, b = pix[x, y]
            a = 255
            if seen[y][x]:
                a = max(0, min(255, int((diff[y][x] - 8) * 255 / (near - 8))))
            o[x, y] = (r, g, b, a)
    # Flow stamps a small Gemini mark in the bottom-right corner; objects never reach it.
    alpha = out.getchannel('A')
    alpha.paste(0, (int(w * .88), int(h * .88), w, h))
    out.putalpha(alpha)
    return out, ('black' if max(bg) < 60 else 'white')


def main(src):
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    index = json.loads(INDEX.read_text()[len(HEADER):].rstrip().rstrip(';')) if INDEX.exists() else []
    counts = {}
    for item in index:
        counts[' '.join(item['keywords'])] = counts.get(' '.join(item['keywords']), 0) + 1
    added = skipped = 0
    for path in sorted(Path(src).iterdir()):
        if path.suffix.lower() not in ('.jpg', '.jpeg', '.png', '.webp'):
            continue
        kws = keywords_from(path.name)
        mascot = any(k in kws for k in ('mascot', 'character', 'chubby'))
        img, bg = cut_out(Image.open(path))
        # Only the red-hoodie mascot was designed; Flow's other creatures were drawn on black.
        if mascot and bg == 'black':
            skipped += 1
            continue
        key = ' '.join(kws)
        if not kws or counts.get(key, 0) >= MAX_VARIANTS:
            skipped += 1
            continue
        counts[key] = counts.get(key, 0) + 1
        slug = re.sub(r'[^a-z0-9]+', '-', key)[:50].strip('-') + f'-{counts[key]}'
        img.save(OUT_DIR / f'{slug}.webp', 'WEBP', quality=86, method=6)
        kws = [k for k in kws if k not in ('mascot', 'character', 'chubby')]
        index.append({'id': slug, 'file': f'library/{slug}.webp', 'keywords': kws, 'kind': 'reaction' if mascot else 'object'})
        added += 1
    INDEX.write_text(HEADER + json.dumps(index, ensure_ascii=False, indent=0) + ';\n')
    print(f'added {added}, skipped {skipped}, library size {len(index)}')


if __name__ == '__main__':
    main(sys.argv[1])
