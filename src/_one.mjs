import {bundle} from '@remotion/bundler';
import {renderMedia,selectComposition} from '@remotion/renderer';
import fs from 'fs';
import {parseTiming,buildProject} from './engine/plan.js';
const [S,lookId]=process.argv.slice(2);
const t=parseTiming(fs.readFileSync(S+'/timingD.json','utf8'));
const serveUrl=await bundle({entryPoint:'/home/user/rctrips/src/remotion/index.jsx',publicDir:'/home/user/rctrips/public'});
const browserExecutable='/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell';
const p=buildProject({...t,duration:t.duration+0.6,settings:{format:'16:9-in-9:16',stickers:'light',lookId}});
p.scenes[3].icon='Cow'; p.scenes[5].icon='';
const inputProps={project:p};
const composition=await selectComposition({serveUrl,id:'Reel',inputProps,browserExecutable});
await renderMedia({composition,serveUrl,inputProps,codec:'h264',outputLocation:`${S}/tplv/${lookId}.mp4`,browserExecutable,crf:20});
console.log('done');
