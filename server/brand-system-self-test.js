import assert from 'node:assert/strict';
import fs from 'node:fs';
import {BRAND_THEME_OPTIONS,BACKGROUND_MODE_OPTIONS,BACKGROUND_STYLE_OPTIONS,ANIMATION_FAMILY_OPTIONS,applyEngagementStylePlans} from '../src/styleEngine.js';
assert.equal(BRAND_THEME_OPTIONS.length,10,'Expected exactly 10 brand themes');
assert.ok(ANIMATION_FAMILY_OPTIONS.length>=20,'Expected at least 20 animation families');
assert.ok(BACKGROUND_MODE_OPTIONS.every(x=>!/gradient/i.test(`${x.id} ${x.label}`)),'Gradient background option found');
assert.ok(BACKGROUND_STYLE_OPTIONS.every(x=>!/gradient|mesh|radial/i.test(`${x.id} ${x.label}`)),'Gradient-like background style found');
const reel=fs.readFileSync(new URL('../src/remotion/Reel.jsx',import.meta.url),'utf8');
const a=reel.indexOf('function SceneBackground');
const b=reel.indexOf('function Scene(',a);
const bgCode=reel.slice(a,b);
assert.ok(!/linear-gradient|radial-gradient/i.test(bgCode),'SceneBackground must never render gradients');
const scenes=Array.from({length:8},(_,i)=>({id:`s${i}`,index:i,text:i===0?'Stop scrolling now':'Simple clean line '+i,keyword:i===0?'Stop':'clean',bg:'#000',fg:'#fff',muted:'#aaa',accent:'#f00',accent2:'#fff',typographyLocked:false,backgroundLocked:false}));
const out=applyEngagementStylePlans(scenes,{brandThemeId:'electric-blue',backgroundMode:'hook-flash',typographyVariety:'maximum',regenCounter:7});
assert.ok(out.every(s=>s.autoHeroFontKey===out[0].autoHeroFontKey),'Hero font changed within one brand');
assert.ok(out.every(s=>s.autoBodyFontKey===out[0].autoBodyFontKey),'Body font changed within one brand');
assert.ok(out.every((s,i)=>i===0||s.animationFamily!==out[i-1].animationFamily),'Animation repeated on adjacent scenes');
console.log('Brand system self-test: PASS');
